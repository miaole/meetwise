/**
 * Bounded local child-process execution for the isolation runner.
 *
 * This module returns only a small stdout buffer on success. Callers must
 * not put captured stderr/stdout in receipts or thrown errors: a failed test
 * may have printed a fixture, endpoint, token or user content. On failure the
 * helper prints a bounded, redacted stderr tail to the operator sink so the
 * exit is diagnosable; the Error itself stays a fixed code. The printed label
 * is only `basename(command)` plus the first subcommand — never raw argv,
 * `--eval` source, or `-e K=V` assignments.
 */
import { spawn, spawnSync } from 'node:child_process';
import { basename } from 'node:path';
import { CREDENTIAL_RULES } from './e2e-static-guards.mjs';

const DEFAULT_MAX_OUTPUT_BYTES = 128 * 1024;
const DEFAULT_STDERR_TAIL_BYTES = 8 * 1024;
const SIGNAL_EXIT_CODES = Object.freeze({ SIGINT: 130, SIGTERM: 143 });
const BEARER_PATTERN = /\bBearer\s+\S+/gi;
const JSON_CREDENTIAL_FIELD_PATTERN = /(["']?)(password|passwd|pwd|token|secret|api[_-]?key|authorization)\1\s*:\s*(["'])((?:\\.|[^\\])*?)\3/gi;
const ENCODED_URL_CANDIDATE_PATTERN = /(?:[A-Za-z][A-Za-z0-9+.-]*)(?:%3A%2F%2F)[^\s"'<>]+/gi;
const BASE64_TOKEN_PATTERN = /\b[A-Za-z0-9+/]{16,}={0,2}\b/g;
const SHORT_ASSIGNMENT_KEYS = 'DB_PASS|MYSQL_PWD|PGPASSWORD';
const KNOWN_SECRET_MIN_LENGTH = 8;

const DEFAULT_REDACTION_RULES = Object.freeze({
  knownValue: true,
  emptyUsername: true,
  multilineUserinfo: true,
  encodedUrl: true,
  base64Credential: true,
  jsonField: true,
  shortAssignmentKeys: true,
});

let registeredSecrets = [];

function normalizeKnownSecrets(values) {
  const list = Array.isArray(values) ? values : (values == null ? [] : [values]);
  return [...new Set(list.filter((value) => typeof value === 'string' && value.length >= KNOWN_SECRET_MIN_LENGTH))];
}

/**
 * Register plaintext secrets generated by this isolated run (for example
 * POSTGRES_PASSWORD and e2e_run_token). Exact values, plus their base64 and
 * URI-encoded forms, are replaced before generic rules run. Returns the
 * previous list so callers can restore it.
 */
export function registerFailureRedactionSecrets(values) {
  const previous = registeredSecrets;
  registeredSecrets = normalizeKnownSecrets(values);
  return previous;
}

export function getFailureRedactionSecrets() {
  return [...registeredSecrets];
}

function resolveRedactionOptions(options = {}) {
  return {
    knownSecrets: normalizeKnownSecrets(options.knownSecrets ?? registeredSecrets),
    rules: { ...DEFAULT_REDACTION_RULES, ...(options.rules ?? {}) },
  };
}

function urlUserinfoPattern(rules) {
  const user = rules.emptyUsername === false ? '([^/\\s:@]+)' : '([^/\\s:@]*)';
  const pass = rules.multilineUserinfo === false ? '([^/\\s@]+)' : '([^/@]*?)';
  return new RegExp(`//${user}:${pass}@`, 'g');
}

function credentialAssignmentPattern(rules) {
  const keys = rules.shortAssignmentKeys === false
    ? 'KEY|TOKEN|SECRET|PASSWORD|AUTHORIZATION'
    : `KEY|TOKEN|SECRET|PASSWORD|AUTHORIZATION|${SHORT_ASSIGNMENT_KEYS}`;
  return new RegExp(`(${keys})\\s*[:=]\\s*\\S+(?:\\s+\\S+)?`, 'gi');
}

function knownSecretForms(secrets) {
  const forms = new Set();
  for (const secret of secrets) {
    forms.add(secret);
    const std = Buffer.from(secret, 'utf8').toString('base64');
    const noPad = std.replace(/=+$/, '');
    forms.add(std);
    forms.add(noPad);
    forms.add(noPad.replace(/\+/g, '-').replace(/\//g, '_'));
    forms.add(encodeURIComponent(secret));
    const encoded = encodeURI(secret);
    if (encoded !== secret) forms.add(encoded);
  }
  return [...forms].filter(Boolean).sort((a, b) => b.length - a.length);
}

function replaceAllExact(text, needle, replacement) {
  if (!needle) return text;
  return text.split(needle).join(replacement);
}

function redactKnownValues(text, secrets) {
  let next = text;
  for (const form of knownSecretForms(secrets)) next = replaceAllExact(next, form, '[REDACTED]');
  return next;
}

function applyUrlUserinfo(text, rules) {
  return text.replace(urlUserinfoPattern(rules), '//$1:***@');
}

function redactPercentEncodedUserinfo(text, rules) {
  return text.replace(ENCODED_URL_CANDIDATE_PATTERN, (match) => {
    try {
      const decoded = decodeURIComponent(match);
      const redacted = applyUrlUserinfo(decoded, rules);
      if (redacted === decoded) return match;
      return encodeURIComponent(redacted);
    } catch {
      return match;
    }
  });
}

function looksLikeBase64Token(token) {
  if (token.length % 4 === 1) return false;
  return /^[A-Za-z0-9+/]+={0,2}$/.test(token);
}

function redactCredentialBearingBase64(text, options) {
  return text.replace(BASE64_TOKEN_PATTERN, (token) => {
    if (!looksLikeBase64Token(token)) return token;
    let decoded;
    try { decoded = Buffer.from(token, 'base64').toString('utf8'); }
    catch { return token; }
    if (!decoded || decoded.includes('\u0000') || /[^\x09\x0a\x0d\x20-\x7e]/.test(decoded)) return token;
    // Only replace when the decoded payload itself is credential-shaped.
    const redacted = redactFailureText(decoded, {
      knownSecrets: [],
      rules: { ...options.rules, knownValue: false, base64Credential: false, encodedUrl: options.rules.encodedUrl },
    });
    return redacted === decoded ? token : '[REDACTED]';
  });
}

function redactJsonCredentialFields(text) {
  return text.replace(JSON_CREDENTIAL_FIELD_PATTERN, (match, open, key, quote) => `${open}${key}${open || ''}:${quote}[REDACTED]${quote}`);
}

/** Shared compose files whose named data volumes the isolated runner must never `down -v`. */
export const PROTECTED_NAMED_VOLUME_COMPOSE = Object.freeze(['docker/compose.mysql-local.yml']);

export class BoundedCommandError extends Error {
  constructor(code) {
    super(code);
    this.name = 'BoundedCommandError';
    this.code = code;
  }
}

/**
 * Operator-safe command label: basename plus the first non-option subcommand.
 * Never include later argv, `--eval` source, or `-e K=V` values.
 */
export function commandLabel(command, args = []) {
  const raw = String(command ?? '').trim() || 'child';
  const name = basename(raw);
  const list = Array.isArray(args) ? args : [];
  const first = list.find((arg) => (
    typeof arg === 'string'
    && /^[A-Za-z0-9][A-Za-z0-9:_-]*$/.test(arg)
  ));
  return first ? `${name} ${first}` : name;
}

/**
 * Redact credential-shaped text before any operator/CI sink sees it.
 * First replaces known run secrets (and their base64 / URI-encoded forms),
 * then applies URL userinfo (including empty usernames and passwords that
 * span newlines), percent-encoded URLs, credential-shaped base64 payloads,
 * CREDENTIAL_RULES, Bearer tokens, KEY/TOKEN/SECRET/PASSWORD/AUTHORIZATION
 * plus DB_PASS/MYSQL_PWD assignments, and JSON password/token/secret fields.
 */
export function redactFailureText(input, options = {}) {
  const { knownSecrets, rules } = resolveRedactionOptions(options);
  let text = String(input ?? '');
  if (rules.knownValue !== false) text = redactKnownValues(text, knownSecrets);
  text = applyUrlUserinfo(text, rules);
  if (rules.encodedUrl !== false) text = redactPercentEncodedUserinfo(text, rules);
  if (rules.base64Credential !== false) text = redactCredentialBearingBase64(text, { rules });
  for (const { pattern } of CREDENTIAL_RULES) {
    const flags = pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`;
    text = text.replace(new RegExp(pattern.source, flags), '[REDACTED]');
  }
  text = text.replace(BEARER_PATTERN, 'Bearer [REDACTED]');
  text = text.replace(credentialAssignmentPattern(rules), (match) => {
    const sep = match.includes('=') ? '=' : ':';
    const key = match.split(/[:=]/)[0];
    return `${key}${sep}[REDACTED]`;
  });
  if (rules.jsonField !== false) text = redactJsonCredentialFields(text);
  return text;
}

/**
 * Keep only the trailing bytes of untrusted child stderr for a failure tail.
 */
export function appendStderrTail(current, chunk, maxBytes = DEFAULT_STDERR_TAIL_BYTES, options = {}) {
  if (!Number.isInteger(maxBytes) || maxBytes <= 0) throw new BoundedCommandError('bounded_command_stderr_tail_limit_invalid');
  const raw = `${current ?? ''}${chunk == null ? '' : chunk.toString('utf8')}`;
  // Redact the full accumulated text first, then take the trailing window so a
  // password split across a newline or the 8KiB cut is not left in the clear.
  const next = options.redact === false ? raw : redactFailureText(raw, options);
  if (next.length <= maxBytes) return next;
  const sliced = next.slice(next.length - maxBytes);
  const newline = sliced.indexOf('\n');
  return newline >= 0 && newline < sliced.length - 1 ? sliced.slice(newline + 1) : sliced;
}

/**
 * Print a bounded, redacted stderr tail on failure. Never attach the tail to
 * thrown errors or receipts. `sink` is injectable so proves can capture the text.
 */
export function writeFailureStderrTail(tail, { exitCode, command, redaction } = {}, sink = process.stderr) {
  const text = redactFailureText(String(tail ?? ''), redaction);
  if (!text) return;
  const label = redactFailureText(String(command ?? 'child'), redaction);
  const bytes = Buffer.byteLength(text);
  const write = typeof sink?.write === 'function' ? (chunk) => sink.write(chunk) : (chunk) => process.stderr.write(chunk);
  write(`ISOLATED_CHILD_STDERR_TAIL exit=${exitCode ?? 'unknown'} command=${label} bytes=${bytes}\n`);
  write(text);
  if (!text.endsWith('\n')) write('\n');
  write('ISOLATED_CHILD_STDERR_TAIL_END\n');
}

/**
 * `docker rm` args for disposable isolated-runner containers.
 * `-v` removes anonymous volumes attached to those containers only.
 * Named volumes (including compose.mysql-local data volumes) are not deleted.
 */
export function disposableDockerRmArgs(names) {
  const list = Array.isArray(names) ? names : [names];
  if (list.length === 0) throw new BoundedCommandError('disposable_docker_rm_names_missing');
  for (const name of list) {
    if (typeof name !== 'string' || !name.trim() || name.startsWith('-') || /\s/.test(name)) {
      throw new BoundedCommandError('disposable_docker_rm_name_invalid');
    }
  }
  return ['rm', '-f', '-v', ...list];
}

function normalizeContainerNames(names) {
  const list = Array.isArray(names) ? names : (names ? [names] : []);
  return list.filter((name) => typeof name === 'string' && name.trim() && !name.startsWith('-') && !/\s/.test(name));
}

/**
 * Synchronously `docker rm -f -v` the disposable containers named by
 * `getContainerNames()`. Used by both SIGINT/SIGTERM handlers and the
 * runner `finally` block so a signal exit takes the same cleanup path.
 * Returns only those named volumes; never prunes and never enumerates
 * unrelated `meetwise-e2e-*` containers.
 */
export function cleanupDisposableContainersSync(names) {
  const list = normalizeContainerNames(names);
  if (list.length === 0) return;
  spawnSync('docker', disposableDockerRmArgs(list), { stdio: 'ignore', timeout: 20_000 });
}

/**
 * Install SIGINT/SIGTERM handlers that clean disposable containers, then
 * exit 130/143. `getContainerNames` is called at signal time so a container
 * created after install is still covered.
 */
export function installDisposableContainerSignalCleanup({ getContainerNames, cleanup } = {}) {
  if (typeof getContainerNames !== 'function') {
    throw new BoundedCommandError('disposable_signal_cleanup_getter_invalid');
  }
  const runCleanup = typeof cleanup === 'function'
    ? cleanup
    : () => cleanupDisposableContainersSync(getContainerNames());
  const handle = (signal) => {
    try { runCleanup(); } catch { /* still exit with the signal code */ }
    process.exit(SIGNAL_EXIT_CODES[signal] ?? 1);
  };
  process.on('SIGINT', () => handle('SIGINT'));
  process.on('SIGTERM', () => handle('SIGTERM'));
  return runCleanup;
}

function terminateProcessGroup(child, signal) {
  try {
    if (child.pid && process.platform !== 'win32') process.kill(-child.pid, signal);
    else child.kill(signal);
  } catch {
    // The child may already have exited between the timeout and the signal.
  }
}

/**
 * Runs one local, non-shell command with a hard deadline.
 *
 * POSIX commands run in their own process group so a wrapper such as Docker
 * cannot leave a local descendant alive after its caller timed out.  A Docker
 * container created by the caller is cleaned by that caller's `finally` block;
 * this helper never enumerates or kills unrelated containers/processes.
 */
export function captureBounded(command, args, {
  cwd,
  env,
  timeoutMs,
  maxOutputBytes = DEFAULT_MAX_OUTPUT_BYTES,
  stderrSink = process.stderr,
  redaction,
} = {}) {
  if (!Number.isInteger(timeoutMs) || timeoutMs <= 0) throw new BoundedCommandError('bounded_command_timeout_invalid');
  if (!Number.isInteger(maxOutputBytes) || maxOutputBytes <= 0) throw new BoundedCommandError('bounded_command_output_limit_invalid');

  return new Promise((resolve, reject) => {
    let child;
    try {
      child = spawn(command, args, {
        cwd,
        env,
        stdio: ['ignore', 'pipe', 'pipe'],
        shell: false,
        detached: process.platform !== 'win32',
      });
    } catch {
      reject(new BoundedCommandError('bounded_command_spawn_failed'));
      return;
    }

    let stdout = '';
    let stdoutBytes = 0;
    let stderrTail = '';
    let settled = false;
    let timedOut = false;
    const label = commandLabel(command, args);
    const emitFailureTail = (exitCode) => {
      writeFailureStderrTail(stderrTail, { exitCode, command: label, redaction }, stderrSink);
    };
    const settle = (outcome) => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      clearTimeout(forceKill);
      if (outcome instanceof Error) reject(outcome);
      else resolve(outcome);
    };
    const timeout = setTimeout(() => {
      timedOut = true;
      terminateProcessGroup(child, 'SIGTERM');
    }, timeoutMs);
    const forceKill = setTimeout(() => {
      if (timedOut) terminateProcessGroup(child, 'SIGKILL');
    }, timeoutMs + 1_000);
    forceKill.unref();

    child.stdout.on('data', (chunk) => {
      stdoutBytes += chunk.length;
      if (stdoutBytes <= maxOutputBytes) stdout += chunk.toString('utf8');
    });
    // Drain stderr so a noisy child cannot block. Keep only a bounded tail
    // and print it on failure; never return it from this helper or attach it
    // to BoundedCommandError (receipts stay free of raw child output).
    child.stderr.on('data', (chunk) => {
      stderrTail = appendStderrTail(stderrTail, chunk, DEFAULT_STDERR_TAIL_BYTES, redaction);
    });
    child.once('error', () => settle(new BoundedCommandError('bounded_command_spawn_failed')));
    child.once('close', (code) => {
      if (timedOut) {
        emitFailureTail('bounded_command_timeout');
        return settle(new BoundedCommandError('bounded_command_timeout'));
      }
      if (stdoutBytes > maxOutputBytes) return settle(new BoundedCommandError('bounded_command_output_exceeded'));
      if (code !== 0) {
        emitFailureTail(code);
        return settle(new BoundedCommandError('bounded_command_exit_nonzero'));
      }
      settle(stdout.trim());
    });
  });
}
